#!/usr/bin/env python3
"""顺序执行 db/migrations/*.sql，并记录到 shared.schema_migration。

用法：
  python scripts/apply_migrations.py                       # 作用于 DATABASE_URL 指向的库
  python scripts/apply_migrations.py --db qiyun_shop_dev_2 # 指定库名
  python scripts/apply_migrations.py --dry-run             # 只列出将执行/跳过的文件

行为：
  - 按文件名排序执行；版本号取文件名第一个下划线前的部分（如 0001）。
  - 每个文件单独一个事务；失败立即停止并返回非零退出码，该文件不被记录。
  - 已记录且 checksum 一致的文件跳过；checksum 不一致视为错误（迁移文件被改动过）。
  - 重复执行安全（幂等）：脚本自身用 CREATE TABLE IF NOT EXISTS 建立记录表。
"""
import argparse
import hashlib
import pathlib
import re
import sys
import time

import psycopg

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.core.config import settings  # noqa: E402

MIGRATIONS = ROOT / "db" / "migrations"
FILE_RE = re.compile(r"^(\d{4})_.+\.sql$")

MIGRATION_TABLE_DDL = """
CREATE TABLE IF NOT EXISTS shared.schema_migration (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version     varchar(32)  NOT NULL,
  file_name   varchar(255) NOT NULL,
  checksum    varchar(64)  NOT NULL,
  applied_at  timestamptz  NOT NULL DEFAULT now(),
  applied_by  varchar(64),
  duration_ms int,
  success     boolean      NOT NULL DEFAULT true,
  CONSTRAINT schema_migration_version_key UNIQUE (version)
)
"""


def split_dsn(url: str) -> dict:
    m = re.match(
        r"postgresql\+psycopg://(?P<user>[^:]+):(?P<pw>[^@]*)@(?P<host>[^:/]+):(?P<port>\d+)/(?P<db>.+)",
        url,
    )
    if not m:
        raise SystemExit(f"无法解析 DATABASE_URL: {url}")
    return m.groupdict()


def dsn_for(parts: dict, db: str) -> str:
    return f"postgresql://{parts['user']}:{parts['pw']}@{parts['host']}:{parts['port']}/{db}"


def collect() -> list[tuple[str, pathlib.Path, str]]:
    if not MIGRATIONS.is_dir():
        return []
    items = []
    for path in sorted(MIGRATIONS.glob("*.sql")):
        match = FILE_RE.match(path.name)
        if not match:
            raise SystemExit(f"迁移文件名不合规（需 0001_描述.sql）：{path.name}")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        items.append((match.group(1), path, digest))
    versions = [v for v, _, _ in items]
    if len(versions) != len(set(versions)):
        raise SystemExit(f"迁移版本号重复：{versions}")
    return items


def applied(conn: psycopg.Connection) -> dict[str, str]:
    rows = conn.execute("SELECT version, checksum FROM shared.schema_migration WHERE success").fetchall()
    return {version: checksum for version, checksum in rows}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default=None, help="目标库名，默认取 DATABASE_URL 中的库名")
    parser.add_argument("--dry-run", action="store_true", help="只打印计划，不执行")
    parser.add_argument("--applied-by", default="apply_migrations.py")
    args = parser.parse_args()

    parts = split_dsn(settings.database_url)
    target = args.db or parts["db"]
    items = collect()

    with psycopg.connect(dsn_for(parts, target), autocommit=False) as conn:
        conn.execute(MIGRATION_TABLE_DDL)
        conn.commit()
        done = applied(conn)

        executed = skipped = 0
        for version, path, digest in items:
            if version in done:
                if done[version] != digest:
                    print(f"ERROR {path.name}: 已执行但 checksum 不一致（迁移文件被改动过）", file=sys.stderr)
                    return 1
                skipped += 1
                if args.dry_run:
                    print(f"skip   {version} {path.name}")
                continue
            if args.dry_run:
                print(f"apply  {version} {path.name}")
                continue
            sql = path.read_text(encoding="utf-8")
            started = time.monotonic()
            try:
                with conn.transaction():
                    conn.execute(sql)
                    elapsed = int((time.monotonic() - started) * 1000)
                    conn.execute(
                        "INSERT INTO shared.schema_migration (version, file_name, checksum, applied_by, duration_ms)"
                        " VALUES (%s, %s, %s, %s, %s)",
                        (version, path.name, digest, args.applied_by, elapsed),
                    )
            except Exception as exc:  # noqa: BLE001 - 失败即停，保留原异常信息
                print(f"ERROR {path.name}: {exc}", file=sys.stderr)
                return 1
            print(f"apply  {version} {path.name} ({elapsed}ms)")
            executed += 1

    if not args.dry_run:
        with psycopg.connect(dsn_for(parts, target)) as conn:
            total = conn.execute(
                "SELECT count(*) FROM information_schema.tables"
                " WHERE table_schema IN ('shared','commerce','knowledge','assistant')"
                " AND table_type = 'BASE TABLE'"
            ).fetchone()[0]
            print(f"done: executed={executed} skipped={skipped} base_tables={total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
