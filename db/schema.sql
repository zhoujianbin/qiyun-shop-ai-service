CREATE TABLE commerce.product_attribute_value (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id   bigint      NOT NULL REFERENCES commerce.product(id) ON DELETE CASCADE,
  attribute_id bigint      NOT NULL REFERENCES commerce.attribute_definition(id),
  value_text   varchar(255) NOT NULL,
  CONSTRAINT product_attribute_value_key UNIQUE (product_id, attribute_id)
);

CREATE TABLE commerce.sku (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint        NOT NULL,
  product_id   bigint        NOT NULL REFERENCES commerce.product(id) ON DELETE CASCADE,
  sku_code     varchar(64)   NOT NULL,
  name         varchar(160)  NOT NULL,
  spec_summary varchar(255),
  price        numeric(14,2) NOT NULL,
  market_price numeric(14,2),
  cost_price   numeric(14,2),
  barcode      varchar(64),
  weight_g     int,
  status       text          NOT NULL DEFAULT 'ON_SALE',
  sort_order   int           NOT NULL DEFAULT 0,
  created_at   timestamptz   NOT NULL DEFAULT now(),
  updated_at   timestamptz   NOT NULL DEFAULT now(),
  version      int           NOT NULL DEFAULT 0,
  CONSTRAINT sku_code_key    UNIQUE (tenant_id, sku_code),
  CONSTRAINT sku_status_ck   CHECK (status IN ('ON_SALE','OFF_SHELF','ARCHIVED')),
  CONSTRAINT sku_price_ck    CHECK (price >= 0 AND (market_price IS NULL OR market_price >= 0) AND (cost_price IS NULL OR cost_price >= 0)),
  CONSTRAINT sku_weight_ck   CHECK (weight_g IS NULL OR weight_g >= 0)
);
CREATE INDEX sku_product_idx ON commerce.sku (product_id, sort_order);
CREATE INDEX sku_barcode_idx ON commerce.sku (tenant_id, barcode) WHERE barcode IS NOT NULL;

CREATE TABLE commerce.sku_attribute_value (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku_id       bigint      NOT NULL REFERENCES commerce.sku(id) ON DELETE CASCADE,
  attribute_id bigint      NOT NULL REFERENCES commerce.attribute_definition(id),
  value_text   varchar(255) NOT NULL,
  CONSTRAINT sku_attribute_value_key UNIQUE (sku_id, attribute_id)
);

CREATE TABLE commerce.price_change_log (
