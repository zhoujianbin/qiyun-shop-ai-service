  changed_by  bigint,
  created_at  timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX price_change_log_sku_idx ON commerce.price_change_log (sku_id, created_at DESC);

-- ==================== 仓库与库存 ====================
CREATE TABLE commerce.warehouse (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint       NOT NULL REFERENCES shared.tenant(id),
  code       varchar(32)  NOT NULL,
  name       varchar(64)  NOT NULL,
  region     varchar(64),
  address    varchar(255),
  priority   int          NOT NULL DEFAULT 100,
  status     text         NOT NULL DEFAULT 'ACTIVE',
  created_at timestamptz  NOT NULL DEFAULT now(),
  updated_at timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT warehouse_code_key  UNIQUE (tenant_id, code),
  CONSTRAINT warehouse_status_ck CHECK (status IN ('ACTIVE','DISABLED'))
);

CREATE TABLE commerce.inventory (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  sku_id          bigint      NOT NULL REFERENCES commerce.sku(id) ON DELETE CASCADE,
  warehouse_id    bigint      NOT NULL REFERENCES commerce.warehouse(id),
  qty_available   int         NOT NULL DEFAULT 0,
  qty_reserved    int         NOT NULL DEFAULT 0,
  qty_in_transit  int         NOT NULL DEFAULT 0,
  safety_stock    int         NOT NULL DEFAULT 0,
  version         int         NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inventory_sku_wh_key UNIQUE (sku_id, warehouse_id),
  CONSTRAINT inventory_qty_ck CHECK (qty_available >= 0 AND qty_reserved >= 0 AND qty_in_transit >= 0)
);
CREATE INDEX inventory_low_stock_idx ON commerce.inventory (tenant_id) WHERE qty_available <= safety_stock;
COMMENT ON COLUMN commerce.inventory.version IS '乐观锁版本号，库存调整必须带版本匹配';

CREATE TABLE commerce.inventory_ledger (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint      NOT NULL,
  sku_id       bigint      NOT NULL REFERENCES commerce.sku(id),
  warehouse_id bigint      NOT NULL REFERENCES commerce.warehouse(id),
  change_type  text        NOT NULL,
  qty_delta    int         NOT NULL,
  qty_after    int         NOT NULL,
  qty_available_after int NOT NULL,
  qty_reserved_after  int NOT NULL,
  ref_type     varchar(32),
  ref_id       varchar(64),
  operator_id  bigint,
  remark       varchar(255),
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT inventory_ledger_type_ck CHECK (change_type IN
    ('PURCHASE_IN','SALE_OUT','RESERVE','RELEASE','RETURN_IN','ADJUST','DAMAGE','TRANSFER_IN','TRANSFER_OUT')),
  CONSTRAINT inventory_ledger_delta_ck CHECK ((change_type IN ('RESERVE','RELEASE')) OR qty_delta <> 0)
);
CREATE INDEX inventory_ledger_sku_idx ON commerce.inventory_ledger (sku_id, created_at DESC);
CREATE INDEX inventory_ledger_ref_idx ON commerce.inventory_ledger (ref_type, ref_id);
COMMENT ON TABLE commerce.inventory_ledger IS '库存只追加流水；qty_after 为在库总量(available+reserved)，锁定/释放不改总量';

CREATE TABLE commerce.inventory_reservation (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint      NOT NULL,
  order_id     bigint,
  order_item_id bigint,
  sku_id       bigint      NOT NULL REFERENCES commerce.sku(id),
  warehouse_id bigint      NOT NULL REFERENCES commerce.warehouse(id),
  qty          int         NOT NULL,
  status       text        NOT NULL DEFAULT 'ACTIVE',
  expires_at   timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),
  released_at  timestamptz,
  CONSTRAINT inventory_reservation_status_ck CHECK (status IN ('ACTIVE','CONSUMED','RELEASED','EXPIRED')),
  CONSTRAINT inventory_reservation_qty_ck CHECK (qty > 0)
);
CREATE INDEX inventory_reservation_order_idx ON commerce.inventory_reservation (order_id);
CREATE INDEX inventory_reservation_active_idx ON commerce.inventory_reservation (status, expires_at) WHERE status = 'ACTIVE';

