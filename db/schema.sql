CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS btree_gin;
CREATE EXTENSION IF NOT EXISTS vector;

CREATE SCHEMA IF NOT EXISTS shared;
CREATE SCHEMA IF NOT EXISTS commerce;
CREATE SCHEMA IF NOT EXISTS knowledge;
COMMENT ON SCHEMA shared IS '身份、权限、渠道、审计、附件、幂等、事件外发';
COMMENT ON SCHEMA commerce IS '第一期电商业务：商品、库存、客户、订单、支付、履约、售后';
COMMENT ON SCHEMA knowledge IS '预留：知识文档与向量检索（本期不写入）';

CREATE OR REPLACE FUNCTION shared.tg_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END $fn$;

-- ---------------- 租户与身份 ----------------
CREATE TABLE shared.tenant (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          varchar(32)  NOT NULL,
  name          varchar(128) NOT NULL,
  status        text         NOT NULL DEFAULT 'ACTIVE',
  created_at    timestamptz  NOT NULL DEFAULT now(),
  updated_at    timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT tenant_code_key  UNIQUE (code),
  CONSTRAINT tenant_status_ck CHECK (status IN ('ACTIVE','SUSPENDED'))
);
COMMENT ON TABLE shared.tenant IS '租户；一期仅一个企业，保留多租户能力';

CREATE TABLE shared.app_user (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id           bigint       NOT NULL REFERENCES shared.tenant(id),
  party               text         NOT NULL,
  username            varchar(64)  NOT NULL,
  email               varchar(128),
  phone               varchar(32),
  password_hash       varchar(255) NOT NULL,
  display_name        varchar(64)  NOT NULL,
  avatar_url          varchar(512),
  status              text         NOT NULL DEFAULT 'ACTIVE',
  is_super_admin      boolean      NOT NULL DEFAULT false,
  failed_login_count  int          NOT NULL DEFAULT 0,
  locked_until        timestamptz,
  last_login_at       timestamptz,
  password_changed_at timestamptz  NOT NULL DEFAULT now(),
  created_at          timestamptz  NOT NULL DEFAULT now(),
  updated_at          timestamptz  NOT NULL DEFAULT now(),
  version             int          NOT NULL DEFAULT 0,
  CONSTRAINT app_user_party_ck  CHECK (party IN ('STAFF','CUSTOMER','GUEST')),
  CONSTRAINT app_user_status_ck CHECK (status IN ('ACTIVE','DISABLED','LOCKED','PENDING')),
  CONSTRAINT app_user_username_key UNIQUE (tenant_id, username)
);
CREATE INDEX app_user_party_idx ON shared.app_user (tenant_id, party, status);
CREATE INDEX app_user_phone_idx ON shared.app_user (tenant_id, phone) WHERE phone IS NOT NULL;
CREATE INDEX app_user_email_idx ON shared.app_user (tenant_id, lower(email)) WHERE email IS NOT NULL;
COMMENT ON TABLE shared.app_user IS '统一身份：员工、客户、游客共表，用 party 区分';

CREATE TABLE shared.app_role (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL REFERENCES shared.tenant(id),
  code        varchar(64) NOT NULL,
  name        varchar(64) NOT NULL,
  description varchar(255),
  is_system   boolean     NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT app_role_code_key UNIQUE (tenant_id, code)
);

CREATE TABLE shared.app_permission (
  id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code   varchar(96) NOT NULL,
  name   varchar(96) NOT NULL,
  module varchar(32) NOT NULL,
  CONSTRAINT app_permission_code_key UNIQUE (code)
);

CREATE TABLE shared.app_role_permission (
  role_id       bigint NOT NULL REFERENCES shared.app_role(id) ON DELETE CASCADE,
  permission_id bigint NOT NULL REFERENCES shared.app_permission(id) ON DELETE CASCADE,
