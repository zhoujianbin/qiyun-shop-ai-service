CREATE VIEW commerce.v_sales_daily AS
SELECT o.tenant_id,
       o.channel_account_id,
       date_trunc('day', o.created_at)::date AS stat_date,
       count(*)                              AS order_count,
       count(*) FILTER (WHERE o.payment_status IN ('PAID','PARTIAL_REFUNDED','REFUNDED')) AS paid_order_count,
       sum(o.payable_amount)                 AS payable_amount,
       sum(o.paid_amount)                    AS paid_amount,
       sum(o.refunded_amount)                AS refunded_amount
FROM commerce.orders o
WHERE o.status <> 'CANCELLED'
GROUP BY o.tenant_id, o.channel_account_id, date_trunc('day', o.created_at)::date;
COMMENT ON VIEW commerce.v_sales_daily IS '按渠道按天的销售汇总';

CREATE VIEW commerce.v_inventory_alert AS
SELECT i.tenant_id, i.sku_id, s.sku_code, s.name AS sku_name, i.warehouse_id, w.name AS warehouse_name,
       i.qty_available, i.qty_reserved, i.safety_stock,
       (i.qty_available - i.qty_reserved) AS sellable_qty
FROM commerce.inventory i
JOIN commerce.sku s ON s.id = i.sku_id
JOIN commerce.warehouse w ON w.id = i.warehouse_id
WHERE i.qty_available <= i.safety_stock;
COMMENT ON VIEW commerce.v_inventory_alert IS '低于安全库存的 SKU';

CREATE VIEW commerce.v_after_sales_sla AS
SELECT a.tenant_id, a.channel_account_id, a.status,
       count(*) AS application_count,
       count(*) FILTER (WHERE a.sla_due_at < now() AND a.status NOT IN ('COMPLETED','REJECTED','CANCELLED')) AS overdue_count,
       avg(extract(epoch FROM (coalesce(a.completed_at, now()) - a.created_at)) / 3600.0) AS avg_hours
FROM commerce.after_sales_application a
GROUP BY a.tenant_id, a.channel_account_id, a.status;

