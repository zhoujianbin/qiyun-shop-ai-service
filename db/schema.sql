  code       varchar(32)  NOT NULL,
  name       varchar(64)  NOT NULL,
  logo_url   varchar(512),
  sort_order int          NOT NULL DEFAULT 0,
  status     text         NOT NULL DEFAULT 'ACTIVE',
  created_at timestamptz  NOT NULL DEFAULT now(),
  updated_at timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT brand_code_key UNIQUE (tenant_id, code),
  CONSTRAINT brand_status_ck CHECK (status IN ('ACTIVE','DISABLED'))
);

CREATE TABLE commerce.category (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint       NOT NULL REFERENCES shared.tenant(id),
  parent_id  bigint       REFERENCES commerce.category(id),
  code       varchar(48)  NOT NULL,
  name       varchar(64)  NOT NULL,
  path       varchar(255) NOT NULL DEFAULT '',
  depth      int          NOT NULL DEFAULT 1,
  sort_order int          NOT NULL DEFAULT 0,
  icon_url   varchar(512),
  status     text         NOT NULL DEFAULT 'ACTIVE',
  created_at timestamptz  NOT NULL DEFAULT now(),
  updated_at timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT category_code_key  UNIQUE (tenant_id, code),
  CONSTRAINT category_status_ck CHECK (status IN ('ACTIVE','DISABLED')),
  CONSTRAINT category_depth_ck  CHECK (depth BETWEEN 1 AND 5)
);
CREATE INDEX category_parent_idx ON commerce.category (parent_id, sort_order);
CREATE INDEX category_path_idx   ON commerce.category (path text_pattern_ops);

CREATE TABLE commerce.product (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint       NOT NULL REFERENCES shared.tenant(id),
  spu_code           varchar(48)  NOT NULL,
  name               varchar(160) NOT NULL,
  brand_id           bigint       REFERENCES commerce.brand(id),
  category_id        bigint       NOT NULL REFERENCES commerce.category(id),
  product_line       varchar(48),
  model_code         varchar(48),
  subtitle           varchar(255),
  description_md     text,
  highlights         jsonb        NOT NULL DEFAULT '[]'::jsonb,
  spec_summary       jsonb        NOT NULL DEFAULT '{}'::jsonb,
  warranty_summary   varchar(255),
  install_required   boolean      NOT NULL DEFAULT false,
  install_notes      text,
  service_scope      varchar(255),
  currency           char(3)      NOT NULL DEFAULT 'CNY',
  min_price          numeric(14,2) NOT NULL DEFAULT 0,
  max_price          numeric(14,2) NOT NULL DEFAULT 0,
  status             text         NOT NULL DEFAULT 'DRAFT',
  published_at       timestamptz,
  sort_order         int          NOT NULL DEFAULT 0,
  created_by         bigint,
  updated_by         bigint,
  created_at         timestamptz  NOT NULL DEFAULT now(),
  updated_at         timestamptz  NOT NULL DEFAULT now(),
  version            int          NOT NULL DEFAULT 0,
  CONSTRAINT product_spu_code_key UNIQUE (tenant_id, spu_code),
  CONSTRAINT product_status_ck    CHECK (status IN ('DRAFT','ON_SALE','OFF_SHELF','ARCHIVED')),
  CONSTRAINT product_price_ck     CHECK (min_price >= 0 AND max_price >= min_price)
);
CREATE INDEX product_category_idx ON commerce.product (tenant_id, category_id, status);
CREATE INDEX product_status_idx   ON commerce.product (tenant_id, status, published_at DESC);
CREATE INDEX product_name_trgm_idx ON commerce.product USING gin (name gin_trgm_ops);
COMMENT ON TABLE commerce.product IS 'SPU 商品主档：企业产品主档字段与销售字段分离';

CREATE TABLE commerce.product_media (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
