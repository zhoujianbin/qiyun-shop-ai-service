CREATE TABLE assistant.pending_action (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  conversation_id bigint      NOT NULL REFERENCES assistant.conversation(id) ON DELETE CASCADE,
  message_id      bigint      NOT NULL REFERENCES assistant.message(id) ON DELETE CASCADE,
  action_key      varchar(64) NOT NULL,
  tool_name       varchar(64) NOT NULL,
  args            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  summary         text        NOT NULL,
  impact          text,
  irreversible    boolean     NOT NULL DEFAULT true,
  status          text        NOT NULL DEFAULT 'PROPOSED',
  expires_at      timestamptz NOT NULL,
  confirmed_at    timestamptz,
  executed_at     timestamptz,
  result          jsonb,
  error_code      varchar(64),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_pending_action_key UNIQUE (conversation_id, action_key),
  CONSTRAINT assistant_pending_action_message_key UNIQUE (conversation_id, message_id),
  CONSTRAINT assistant_pending_action_status_ck CHECK (
    status IN ('PROPOSED', 'CONFIRMED', 'EXECUTED', 'FAILED', 'EXPIRED', 'CANCELLED'))
);
CREATE INDEX assistant_pending_action_conversation_idx ON assistant.pending_action (conversation_id, created_at DESC);
CREATE INDEX assistant_pending_action_expiry_idx ON assistant.pending_action (status, expires_at) WHERE status = 'PROPOSED';
COMMENT ON TABLE assistant.pending_action IS '写操作待确认动作；UNIQUE(conversation_id, message_id) 保证单轮最多一个写操作';

CREATE TABLE assistant.tool_call (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  message_id      bigint      NOT NULL REFERENCES assistant.message(id) ON DELETE CASCADE,
