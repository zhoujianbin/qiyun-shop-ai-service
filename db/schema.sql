CREATE INDEX assistant_tool_call_tool_idx ON assistant.tool_call (tenant_id, tool_name, created_at DESC);
COMMENT ON TABLE assistant.tool_call IS '工具调用留痕；args 脱敏后保存；评测按 tool_name 统计成功率与时延';

