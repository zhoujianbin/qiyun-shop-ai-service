CREATE TABLE shared.staff_channel_scope (
  user_id            bigint      NOT NULL REFERENCES shared.app_user(id) ON DELETE CASCADE,
  channel_account_id bigint      NOT NULL REFERENCES shared.channel_account(id) ON DELETE CASCADE,
  granted_by         bigint      REFERENCES shared.app_user(id),
  granted_at         timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, channel_account_id)
);
COMMENT ON TABLE shared.staff_channel_scope IS '员工渠道数据范围；管理员角色默认全渠道';

CREATE TABLE shared.refresh_token (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     bigint       NOT NULL REFERENCES shared.app_user(id) ON DELETE CASCADE,
  token_hash  varchar(128) NOT NULL,
  family_id   uuid         NOT NULL DEFAULT gen_random_uuid(),
  expires_at  timestamptz  NOT NULL,
  revoked_at  timestamptz,
  replaced_by bigint       REFERENCES shared.refresh_token(id),
  user_agent  varchar(255),
  ip          inet,
  created_at  timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT refresh_token_hash_key UNIQUE (token_hash)
);
CREATE INDEX refresh_token_user_idx ON shared.refresh_token (user_id, expires_at DESC);

CREATE TABLE shared.audit_log (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint      NOT NULL,
  actor_type         text        NOT NULL,
  actor_id           bigint,
  actor_label        varchar(128),
  action             varchar(64) NOT NULL,
  resource_type      varchar(48) NOT NULL,
  resource_id        varchar(64),
  channel_account_id bigint,
  before_data        jsonb,
  after_data         jsonb,
  request_id         varchar(64),
  ip                 inet,
  user_agent         varchar(255),
  created_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT audit_log_actor_type_ck CHECK (actor_type IN ('STAFF','CUSTOMER','GUEST','SYSTEM'))
);
CREATE INDEX audit_log_resource_idx ON shared.audit_log (resource_type, resource_id, created_at DESC);
CREATE INDEX audit_log_actor_idx    ON shared.audit_log (actor_id, created_at DESC);
CREATE INDEX audit_log_created_idx  ON shared.audit_log (created_at DESC);
CREATE INDEX audit_log_action_idx   ON shared.audit_log (action, created_at DESC);
COMMENT ON TABLE shared.audit_log IS '只追加审计流水；写操作必须落库，禁止更新删除';

CREATE TABLE shared.idempotency_record (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint       NOT NULL,
  idem_key        varchar(128) NOT NULL,
  user_id         bigint,
  method          varchar(8)   NOT NULL,
  path            varchar(255) NOT NULL,
  request_hash    varchar(64)  NOT NULL,
  state           text         NOT NULL DEFAULT 'IN_PROGRESS',
  response_status int,
  response_body   jsonb,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  completed_at    timestamptz,
  expires_at      timestamptz  NOT NULL DEFAULT now() + interval '24 hours',
  CONSTRAINT idempotency_record_state_ck CHECK (state IN ('IN_PROGRESS','COMPLETED','FAILED')),
  CONSTRAINT idempotency_record_key UNIQUE (tenant_id, idem_key)
);
CREATE INDEX idempotency_record_expires_idx ON shared.idempotency_record (expires_at);
COMMENT ON TABLE shared.idempotency_record IS '写接口幂等记录：同 key 同指纹回放，异指纹返回 409';

CREATE TABLE shared.outbox_event (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint       NOT NULL,
  event_type     varchar(64)  NOT NULL,
  aggregate_type varchar(48)  NOT NULL,
  aggregate_id   varchar(64)  NOT NULL,
  payload        jsonb        NOT NULL,
  status         text         NOT NULL DEFAULT 'PENDING',
  attempts       int          NOT NULL DEFAULT 0,
  available_at   timestamptz  NOT NULL DEFAULT now(),
  published_at   timestamptz,
  last_error     text,
  request_id     varchar(64),
  created_at     timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT outbox_event_status_ck CHECK (status IN ('PENDING','PUBLISHED','FAILED','DEAD'))
);
CREATE INDEX outbox_event_pending_idx ON shared.outbox_event (status, available_at) WHERE status = 'PENDING';
CREATE INDEX outbox_event_aggregate_idx ON shared.outbox_event (aggregate_type, aggregate_id);
COMMENT ON TABLE shared.outbox_event IS '事务内写入的领域事件；供下游消费，本期只写';

CREATE TABLE shared.attachment (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint       NOT NULL,
  owner_type      varchar(48)  NOT NULL,
  owner_id        varchar(64),
  file_name       varchar(255) NOT NULL,
  content_type    varchar(128) NOT NULL,
  size_bytes      bigint       NOT NULL,
  storage_key     varchar(512) NOT NULL,
  checksum_sha256 varchar(64)  NOT NULL,
  uploaded_by     bigint,
  status          text         NOT NULL DEFAULT 'READY',
  created_at      timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT attachment_status_ck CHECK (status IN ('PENDING','READY','REJECTED','DELETED')),
  CONSTRAINT attachment_size_ck   CHECK (size_bytes > 0 AND size_bytes <= 20971520)
);
CREATE INDEX attachment_owner_idx ON shared.attachment (owner_type, owner_id);

CREATE TRIGGER trg_tenant_touch  BEFORE UPDATE ON shared.tenant          FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();
CREATE TRIGGER trg_user_touch    BEFORE UPDATE ON shared.app_user        FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();
CREATE TRIGGER trg_role_touch    BEFORE UPDATE ON shared.app_role        FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();
CREATE TRIGGER trg_channel_touch BEFORE UPDATE ON shared.channel_account FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

