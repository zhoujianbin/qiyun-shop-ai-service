  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  category_id bigint      REFERENCES commerce.category(id),
  code        varchar(48) NOT NULL,
  name        varchar(64) NOT NULL,
  data_type   text        NOT NULL DEFAULT 'TEXT',
  unit        varchar(16),
  is_spec     boolean     NOT NULL DEFAULT false,
  is_required boolean     NOT NULL DEFAULT false,
  options     jsonb       NOT NULL DEFAULT '[]'::jsonb,
  sort_order  int         NOT NULL DEFAULT 0,
  CONSTRAINT attribute_definition_code_key UNIQUE (tenant_id, code),
  CONSTRAINT attribute_definition_type_ck CHECK (data_type IN ('TEXT','NUMBER','BOOL','ENUM','DATE'))
