  CONSTRAINT channel_account_type_ck  CHECK (channel_type IN ('OFFICIAL_MALL','ECOMMERCE','RETAIL','OTHER','ECOM_FLAGSHIP','AUTHORIZED_RETAIL')),
  CONSTRAINT channel_account_status_ck CHECK (status IN ('ACTIVE','DISABLED'))
