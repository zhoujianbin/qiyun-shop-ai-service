-- 0010 四期：assistant 待确认动作与工具调用留痕（6 → 8 表）
-- 幂等：CREATE TABLE / INDEX IF NOT EXISTS；触发器先 DROP IF EXISTS 再建。
-- 回滚：DROP TABLE assistant.tool_call, assistant.pending_action;
-- 说明：不改 0007 任何既有表；handoff.reason 的 CHECK 枚举保持不动（工具失败沿用 MODEL_ERROR）。

CREATE TABLE IF NOT EXISTS assistant.pending_action (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  conversation_id bigint      NOT NULL REFERENCES assistant.conversation(id) ON DELETE CASCADE,
  message_id      bigint      NOT NULL REFERENCES assistant.message(id) ON DELETE CASCADE,
  action_key      varchar(64) NOT NULL,
  tool_name       varchar(64) NOT NULL,
  args            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  summary         text        NOT NULL,
  impact          text,
  irreversible    boolean     NOT NULL DEFAULT true,
  status          text        NOT NULL DEFAULT 'PROPOSED',
  expires_at      timestamptz NOT NULL,
  confirmed_at    timestamptz,
  executed_at     timestamptz,
  result          jsonb,
  error_code      varchar(64),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_pending_action_key UNIQUE (conversation_id, action_key),
  CONSTRAINT assistant_pending_action_message_key UNIQUE (conversation_id, message_id),
  CONSTRAINT assistant_pending_action_status_ck CHECK (
    status IN ('PROPOSED', 'CONFIRMED', 'EXECUTED', 'FAILED', 'EXPIRED', 'CANCELLED'))
);
CREATE INDEX IF NOT EXISTS assistant_pending_action_conversation_idx
  ON assistant.pending_action (conversation_id, created_at DESC);
CREATE INDEX IF NOT EXISTS assistant_pending_action_expiry_idx
  ON assistant.pending_action (status, expires_at) WHERE status = 'PROPOSED';

DROP TRIGGER IF EXISTS trg_assistant_pending_action_touch ON assistant.pending_action;
CREATE TRIGGER trg_assistant_pending_action_touch BEFORE UPDATE ON assistant.pending_action
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE assistant.pending_action IS '写操作待确认动作；UNIQUE(conversation_id, message_id) 保证单轮最多一个写操作';

CREATE TABLE IF NOT EXISTS assistant.tool_call (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  message_id      bigint      NOT NULL REFERENCES assistant.message(id) ON DELETE CASCADE,
  conversation_id bigint      NOT NULL REFERENCES assistant.conversation(id) ON DELETE CASCADE,
  tool_name       varchar(64) NOT NULL,
  args            jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status          text        NOT NULL DEFAULT 'OK',
  latency_ms      int,
  error_code      varchar(64),
  proposal_id     bigint      REFERENCES assistant.pending_action(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_tool_call_status_ck CHECK (status IN ('OK', 'FAILED', 'REJECTED', 'TIMEOUT'))
);
CREATE INDEX IF NOT EXISTS assistant_tool_call_message_idx ON assistant.tool_call (message_id);
CREATE INDEX IF NOT EXISTS assistant_tool_call_tool_idx ON assistant.tool_call (tenant_id, tool_name, created_at DESC);

COMMENT ON TABLE assistant.tool_call IS '工具调用留痕；args 脱敏后保存；评测按 tool_name 统计成功率与时延';
