-- 0007 三期：assistant schema（会话 / 消息 / 引用 / 转人工 / 身份核验 / 问答留痕）
-- 幂等：CREATE SCHEMA / TABLE / INDEX IF NOT EXISTS；触发器先 DROP IF EXISTS 再建。
-- 回滚：DROP SCHEMA assistant CASCADE;（会话数据，无业务依赖）

CREATE SCHEMA IF NOT EXISTS assistant;

CREATE TABLE IF NOT EXISTS assistant.conversation (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint      NOT NULL,
  conversation_no    varchar(32) NOT NULL,
  user_id            bigint      NOT NULL REFERENCES shared.app_user(id),
  party              text        NOT NULL,
  channel_account_id bigint      REFERENCES shared.channel_account(id),
  title              varchar(120),
  status             text        NOT NULL DEFAULT 'OPEN',
  ai_paused          boolean     NOT NULL DEFAULT false,
  message_count      int         NOT NULL DEFAULT 0,
  last_message_at    timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_conversation_no_key UNIQUE (tenant_id, conversation_no),
  CONSTRAINT assistant_conversation_party_ck CHECK (party IN ('CUSTOMER','GUEST')),
  CONSTRAINT assistant_conversation_status_ck CHECK (status IN ('OPEN','CLOSED'))
);
CREATE INDEX IF NOT EXISTS assistant_conversation_user_idx
  ON assistant.conversation (tenant_id, user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS assistant_conversation_queue_idx
  ON assistant.conversation (tenant_id, status, last_message_at DESC);

DROP TRIGGER IF EXISTS trg_assistant_conversation_touch ON assistant.conversation;
CREATE TRIGGER trg_assistant_conversation_touch BEFORE UPDATE ON assistant.conversation
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE assistant.conversation IS '客服会话；ai_paused 与转人工联动（客服接单后 AI 停止自动回答）';

CREATE TABLE IF NOT EXISTS assistant.message (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  conversation_id   bigint      NOT NULL REFERENCES assistant.conversation(id) ON DELETE CASCADE,
  seq               int         NOT NULL,
  role              text        NOT NULL,
  content           text        NOT NULL DEFAULT '',
  status            text        NOT NULL DEFAULT 'DONE',
  client_msg_id     varchar(64),
  model             varchar(64),
  prompt_tokens     int,
  completion_tokens int,
  latency_ms        int,
  metadata          jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_message_seq_key UNIQUE (conversation_id, seq),
  CONSTRAINT assistant_message_role_ck CHECK (role IN ('USER','ASSISTANT','AGENT','SYSTEM')),
  CONSTRAINT assistant_message_status_ck CHECK (status IN ('STREAMING','DONE','FAILED','REFUSED'))
);
CREATE UNIQUE INDEX IF NOT EXISTS assistant_message_client_uidx
  ON assistant.message (conversation_id, client_msg_id) WHERE client_msg_id IS NOT NULL;

DROP TRIGGER IF EXISTS trg_assistant_message_touch ON assistant.message;
CREATE TRIGGER trg_assistant_message_touch BEFORE UPDATE ON assistant.message
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE assistant.message IS '会话消息；client_msg_id 唯一键保证重发幂等，metadata 存 plan 与 feedback';

CREATE TABLE IF NOT EXISTS assistant.citation (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  message_id  bigint      NOT NULL REFERENCES assistant.message(id) ON DELETE CASCADE,
  chunk_id    bigint,
  document_id varchar(48) NOT NULL,
  version     int         NOT NULL,
  title_path  varchar(512),
  line_start  int,
  line_end    int,
  snippet     text,
  rank        int         NOT NULL,
  entity_tags jsonb       NOT NULL DEFAULT '[]'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_citation_rank_key UNIQUE (message_id, rank)
);
CREATE INDEX IF NOT EXISTS assistant_citation_document_idx
  ON assistant.citation (tenant_id, document_id);
COMMENT ON TABLE assistant.citation IS '回答引用：由服务端从检索命中生成，可回指二期切片；entity_tags 为四期本体预埋';

CREATE TABLE IF NOT EXISTS assistant.handoff (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  conversation_id bigint      NOT NULL REFERENCES assistant.conversation(id) ON DELETE CASCADE,
  reason          text        NOT NULL,
  status          text        NOT NULL DEFAULT 'OPEN',
  assignee_id     bigint,
  claimed_at      timestamptz,
  closed_at       timestamptz,
  summary         text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_handoff_reason_ck CHECK (reason IN ('USER_REQUEST','HIGH_RISK_RULE','IDENTITY_FAILED','NO_HIT','MODEL_ERROR')),
  CONSTRAINT assistant_handoff_status_ck CHECK (status IN ('OPEN','CLAIMED','CLOSED'))
);
CREATE UNIQUE INDEX IF NOT EXISTS assistant_handoff_open_uidx
  ON assistant.handoff (conversation_id) WHERE status IN ('OPEN','CLAIMED');
CREATE INDEX IF NOT EXISTS assistant_handoff_queue_idx
  ON assistant.handoff (tenant_id, status, created_at);

DROP TRIGGER IF EXISTS trg_assistant_handoff_touch ON assistant.handoff;
CREATE TRIGGER trg_assistant_handoff_touch BEFORE UPDATE ON assistant.handoff
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE assistant.handoff IS '转人工交接；同一会话同时只允许一个未决记录，认领制';

CREATE TABLE IF NOT EXISTS assistant.identity_verification (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  conversation_id bigint      NOT NULL REFERENCES assistant.conversation(id) ON DELETE CASCADE,
  order_no        varchar(32) NOT NULL,
  phone_tail      char(4)     NOT NULL,
  order_id        bigint      REFERENCES commerce.orders(id) ON DELETE SET NULL,
  customer_id     bigint      REFERENCES commerce.customer_profile(id) ON DELETE SET NULL,
  status          text        NOT NULL,
  attempts        int         NOT NULL DEFAULT 0,
  expires_at      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assistant_identity_status_ck CHECK (status IN ('VERIFIED','FAILED')),
  CONSTRAINT assistant_identity_phone_ck CHECK (phone_tail ~ '^[0-9]{4}$')
);
CREATE INDEX IF NOT EXISTS assistant_identity_conversation_idx
  ON assistant.identity_verification (conversation_id, created_at DESC);
COMMENT ON TABLE assistant.identity_verification IS '身份核验：只存收货手机后四位，不存完整手机号';

CREATE TABLE IF NOT EXISTS assistant.retrieval_trace (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  message_id bigint      NOT NULL REFERENCES assistant.message(id) ON DELETE CASCADE,
  query      text        NOT NULL,
  filters    jsonb       NOT NULL DEFAULT '{}'::jsonb,
  intent     varchar(32),
  hit_count  int         NOT NULL DEFAULT 0,
  hits       jsonb       NOT NULL DEFAULT '[]'::jsonb,
  latency_ms int,
  model      varchar(64),
  tokens     int,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS assistant_retrieval_trace_message_idx
  ON assistant.retrieval_trace (message_id);
COMMENT ON TABLE assistant.retrieval_trace IS '问答链路留痕：查询、命中、耗时、模型与用量，随消息级联删除';
