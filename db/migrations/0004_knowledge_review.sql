-- 0004 审核任务与批注
-- 幂等：CREATE TABLE / INDEX IF NOT EXISTS，触发器先 DROP IF EXISTS 再建。
-- 回滚：DROP TABLE knowledge.review_comment; DROP TABLE knowledge.review_task;

CREATE TABLE IF NOT EXISTS knowledge.review_task (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id           bigint      NOT NULL,
  document_version_id bigint      NOT NULL REFERENCES knowledge.document_version(id) ON DELETE CASCADE,
  assignee_id         bigint,
  status              text        NOT NULL DEFAULT 'PENDING',
  due_at              timestamptz,
  decision            text,
  decided_at          timestamptz,
  note                text,
  self_review         boolean     NOT NULL DEFAULT false,
  created_by          bigint,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT knowledge_review_task_status_ck CHECK (status IN ('PENDING','CLAIMED','DECIDED','CANCELLED')),
  CONSTRAINT knowledge_review_task_decision_ck CHECK (decision IS NULL OR decision IN ('APPROVED','CHANGES_REQUESTED','REJECTED'))
);
CREATE UNIQUE INDEX IF NOT EXISTS knowledge_review_task_open_uidx
  ON knowledge.review_task (document_version_id) WHERE status IN ('PENDING','CLAIMED');
CREATE INDEX IF NOT EXISTS knowledge_review_task_queue_idx
  ON knowledge.review_task (tenant_id, status, created_at);

DROP TRIGGER IF EXISTS trg_knowledge_review_task_touch ON knowledge.review_task;
CREATE TRIGGER trg_knowledge_review_task_touch BEFORE UPDATE ON knowledge.review_task
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE knowledge.review_task IS '审核任务；同一版本同时只允许一个未决任务';

CREATE TABLE IF NOT EXISTS knowledge.review_comment (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  version_id bigint      NOT NULL REFERENCES knowledge.document_version(id) ON DELETE CASCADE,
  task_id    bigint      REFERENCES knowledge.review_task(id) ON DELETE SET NULL,
  author_id  bigint,
  anchor     jsonb       NOT NULL DEFAULT '{}'::jsonb,
  content    text        NOT NULL,
  resolved   boolean     NOT NULL DEFAULT false,
  parent_id  bigint      REFERENCES knowledge.review_comment(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS knowledge_review_comment_version_idx
  ON knowledge.review_comment (version_id, created_at);
COMMENT ON TABLE knowledge.review_comment IS '审核批注；anchor 支持标题路径/切片序号/字符区间';
