-- 0009 四期：ontology schema（实体 / 关系 / 别名 / 实体标签 / 切片映射）
-- 幂等：CREATE SCHEMA / TABLE / INDEX IF NOT EXISTS；触发器先 DROP IF EXISTS 再建。
-- 回滚：DROP SCHEMA ontology CASCADE;（本体数据，无业务表依赖）

CREATE SCHEMA IF NOT EXISTS ontology;
COMMENT ON SCHEMA ontology IS '四期：本体（实体、关系、别名、实体标签、切片映射）';

CREATE TABLE IF NOT EXISTS ontology.entity (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  code       varchar(64) NOT NULL,
  kind       text        NOT NULL,
  name       varchar(160) NOT NULL,
  summary    text,
  attrs      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status     text        NOT NULL DEFAULT 'DRAFT',
  source     text        NOT NULL DEFAULT 'manual',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ontology_entity_code_key UNIQUE (tenant_id, code),
  CONSTRAINT ontology_entity_kind_ck CHECK (kind IN ('product', 'accessory', 'part', 'fault', 'action', 'policy')),
  CONSTRAINT ontology_entity_status_ck CHECK (status IN ('DRAFT', 'APPROVED', 'DEPRECATED')),
  CONSTRAINT ontology_entity_source_ck CHECK (source IN ('manual', 'import'))
);
CREATE INDEX IF NOT EXISTS ontology_entity_kind_idx ON ontology.entity (tenant_id, kind, status);

DROP TRIGGER IF EXISTS trg_ontology_entity_touch ON ontology.entity;
CREATE TRIGGER trg_ontology_entity_touch BEFORE UPDATE ON ontology.entity
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE ontology.entity IS '本体实体；code 与结构化规则同源（如 QL-L3P），只有 APPROVED 参与检索与回答';

CREATE TABLE IF NOT EXISTS ontology.relation (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  src_entity_id bigint      NOT NULL REFERENCES ontology.entity(id) ON DELETE CASCADE,
  dst_entity_id bigint      NOT NULL REFERENCES ontology.entity(id) ON DELETE CASCADE,
  predicate     text        NOT NULL,
  weight        numeric(4,2) NOT NULL DEFAULT 1.00,
  attrs         jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status        text        NOT NULL DEFAULT 'DRAFT',
  source        text        NOT NULL DEFAULT 'manual',
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ontology_relation_key UNIQUE (tenant_id, src_entity_id, predicate, dst_entity_id),
  CONSTRAINT ontology_relation_self_ck CHECK (src_entity_id <> dst_entity_id),
  CONSTRAINT ontology_relation_predicate_ck CHECK (
    predicate IN ('PART_OF', 'SYMPTOM_OF', 'REMEDY', 'COVERED_BY', 'GOVERNED_BY', 'ESCALATES_TO', 'ALIAS_OF')),
  CONSTRAINT ontology_relation_status_ck CHECK (status IN ('DRAFT', 'APPROVED', 'DEPRECATED')),
  CONSTRAINT ontology_relation_source_ck CHECK (source IN ('manual', 'import'))
);
CREATE INDEX IF NOT EXISTS ontology_relation_src_idx ON ontology.relation (tenant_id, src_entity_id, status);
CREATE INDEX IF NOT EXISTS ontology_relation_dst_idx ON ontology.relation (tenant_id, dst_entity_id, status);

DROP TRIGGER IF EXISTS trg_ontology_relation_touch ON ontology.relation;
CREATE TRIGGER trg_ontology_relation_touch BEFORE UPDATE ON ontology.relation
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE ontology.relation IS '本体关系；递归 CTE 遍历带 depth 与路径去重防环';

CREATE TABLE IF NOT EXISTS ontology.alias (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint       NOT NULL,
  entity_id  bigint       NOT NULL REFERENCES ontology.entity(id) ON DELETE CASCADE,
  alias      varchar(160) NOT NULL,
  confidence text         NOT NULL DEFAULT 'HIGH',
  status     text         NOT NULL DEFAULT 'DRAFT',
  source     text         NOT NULL DEFAULT 'manual',
  created_at timestamptz  NOT NULL DEFAULT now(),
  updated_at timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT ontology_alias_key UNIQUE (tenant_id, alias, entity_id),
  CONSTRAINT ontology_alias_confidence_ck CHECK (confidence IN ('HIGH', 'LOW')),
  CONSTRAINT ontology_alias_status_ck CHECK (status IN ('DRAFT', 'APPROVED', 'DEPRECATED')),
  CONSTRAINT ontology_alias_source_ck CHECK (source IN ('manual', 'import'))
);
CREATE INDEX IF NOT EXISTS ontology_alias_lookup_idx ON ontology.alias (tenant_id, alias, status);

DROP TRIGGER IF EXISTS trg_ontology_alias_touch ON ontology.alias;
CREATE TRIGGER trg_ontology_alias_touch BEFORE UPDATE ON ontology.alias
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE ontology.alias IS '实体的自然语言别名；归一采用最长匹配优先，避免上位词误判';

CREATE TABLE IF NOT EXISTS ontology.entity_tag (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id  bigint      NOT NULL,
  entity_id  bigint      NOT NULL REFERENCES ontology.entity(id) ON DELETE CASCADE,
  tag        varchar(32) NOT NULL,
  value      varchar(96) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ontology_entity_tag_key UNIQUE (tenant_id, entity_id, tag, value)
);
CREATE INDEX IF NOT EXISTS ontology_entity_tag_lookup_idx ON ontology.entity_tag (tenant_id, tag, value);

COMMENT ON TABLE ontology.entity_tag IS '实体标签：把本体映射到二期已有检索过滤键（如 product_scope）';

CREATE TABLE IF NOT EXISTS ontology.chunk_entity (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  document_id varchar(48) NOT NULL,
  version     int         NOT NULL,
  chunk_ord   int         NOT NULL,
  chunk_id    bigint,
  entity_id   bigint      NOT NULL REFERENCES ontology.entity(id) ON DELETE CASCADE,
  method      text        NOT NULL DEFAULT 'manual',
  confidence  text        NOT NULL DEFAULT 'HIGH',
  status      text        NOT NULL DEFAULT 'DRAFT',
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ontology_chunk_entity_key UNIQUE (document_id, version, chunk_ord, entity_id),
  CONSTRAINT ontology_chunk_entity_method_ck CHECK (method IN ('alias', 'regex', 'manual')),
  CONSTRAINT ontology_chunk_entity_confidence_ck CHECK (confidence IN ('HIGH', 'LOW')),
  CONSTRAINT ontology_chunk_entity_status_ck CHECK (status IN ('DRAFT', 'APPROVED', 'DEPRECATED'))
);
CREATE INDEX IF NOT EXISTS ontology_chunk_entity_entity_idx ON ontology.chunk_entity (tenant_id, entity_id, status);
CREATE INDEX IF NOT EXISTS ontology_chunk_entity_chunk_idx ON ontology.chunk_entity (chunk_id);

COMMENT ON TABLE ontology.chunk_entity IS '切片与实体映射；逻辑键为 document_id+version+chunk_ord，chunk_id 仅作冗余加速，换版按逻辑键重挂不重跑抽取';
