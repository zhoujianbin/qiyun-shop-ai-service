-- 0003 结构化规则与规则冲突
-- 幂等：CREATE TABLE / INDEX IF NOT EXISTS，触发器先 DROP IF EXISTS 再建。
-- 回滚：DROP TABLE knowledge.rule_conflict; DROP TABLE knowledge.rule;

CREATE TABLE IF NOT EXISTS knowledge.rule (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint       NOT NULL,
  rule_id         varchar(48)  NOT NULL,
  source_kind     text         NOT NULL DEFAULT 'manual',
  condition       jsonb        NOT NULL DEFAULT '{}'::jsonb,
  action          jsonb        NOT NULL DEFAULT '{}'::jsonb,
  forbid          jsonb        NOT NULL DEFAULT '[]'::jsonb,
  priority        int          NOT NULL DEFAULT 100,
  status          text         NOT NULL DEFAULT 'DRAFT',
  effective_from  timestamptz,
  effective_until timestamptz,
  conflict_group  varchar(48),
  source_file     varchar(255),
  source_line     int,
  created_by      bigint,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT knowledge_rule_id_key UNIQUE (tenant_id, rule_id),
  CONSTRAINT knowledge_rule_source_ck CHECK (source_kind IN ('policy','warranty','escalation','manual')),
  CONSTRAINT knowledge_rule_status_ck CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED'))
);
CREATE INDEX IF NOT EXISTS knowledge_rule_group_idx  ON knowledge.rule (tenant_id, conflict_group, status);
CREATE INDEX IF NOT EXISTS knowledge_rule_status_idx ON knowledge.rule (tenant_id, status, priority DESC);

DROP TRIGGER IF EXISTS trg_knowledge_rule_touch ON knowledge.rule;
CREATE TRIGGER trg_knowledge_rule_touch BEFORE UPDATE ON knowledge.rule
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE knowledge.rule IS '结构化规则：一叶子规则一行，condition 键限定 6 个语义键';

CREATE TABLE IF NOT EXISTS knowledge.rule_conflict (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint      NOT NULL,
  rule_a_id     bigint      NOT NULL REFERENCES knowledge.rule(id) ON DELETE CASCADE,
  rule_b_id     bigint      NOT NULL REFERENCES knowledge.rule(id) ON DELETE CASCADE,
  conflict_type varchar(48) NOT NULL,
  severity      text        NOT NULL DEFAULT 'WARN',
  status        text        NOT NULL DEFAULT 'OPEN',
  detail        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  detected_at   timestamptz NOT NULL DEFAULT now(),
  resolved_by   bigint,
  resolved_at   timestamptz,
  CONSTRAINT knowledge_rule_conflict_pair_key UNIQUE (rule_a_id, rule_b_id, conflict_type),
  CONSTRAINT knowledge_rule_conflict_severity_ck CHECK (severity IN ('BLOCK','WARN')),
  CONSTRAINT knowledge_rule_conflict_status_ck CHECK (status IN ('OPEN','RESOLVED','IGNORED')),
  CONSTRAINT knowledge_rule_conflict_order_ck CHECK (rule_a_id < rule_b_id)
);
CREATE INDEX IF NOT EXISTS knowledge_rule_conflict_status_idx
  ON knowledge.rule_conflict (tenant_id, status, severity);
COMMENT ON TABLE knowledge.rule_conflict IS '规则冲突：BLOCK 未解决时禁止发布';
