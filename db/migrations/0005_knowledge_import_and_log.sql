-- 0005 导入任务与检索日志
-- 幂等：CREATE TABLE / INDEX IF NOT EXISTS，触发器先 DROP IF EXISTS 再建。
-- 回滚：DROP TABLE knowledge.retrieval_log; DROP TABLE knowledge.import_job;

CREATE TABLE IF NOT EXISTS knowledge.import_job (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  source_type     text        NOT NULL DEFAULT 'MD_BUNDLE',
  file_name       varchar(255),
  checksum        varchar(64),
  status          text        NOT NULL DEFAULT 'PENDING',
  total           int         NOT NULL DEFAULT 0,
  succeeded       int         NOT NULL DEFAULT 0,
  failed          int         NOT NULL DEFAULT 0,
  skipped         int         NOT NULL DEFAULT 0,
  errors          jsonb       NOT NULL DEFAULT '[]'::jsonb,
  idempotency_key varchar(128),
  created_by      bigint,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT knowledge_import_job_source_ck CHECK (source_type IN ('MD_BUNDLE','RULE_YAML')),
  CONSTRAINT knowledge_import_job_status_ck CHECK (status IN ('PENDING','RUNNING','DONE','PARTIAL','FAILED'))
);
CREATE UNIQUE INDEX IF NOT EXISTS knowledge_import_job_idem_uidx
  ON knowledge.import_job (tenant_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

DROP TRIGGER IF EXISTS trg_knowledge_import_job_touch ON knowledge.import_job;
CREATE TRIGGER trg_knowledge_import_job_touch BEFORE UPDATE ON knowledge.import_job
  FOR EACH ROW EXECUTE FUNCTION shared.tg_touch_updated_at();

COMMENT ON TABLE knowledge.import_job IS '导入任务：total/succeeded/failed/skipped/errors 五字段是导入结果证据';

CREATE TABLE IF NOT EXISTS knowledge.retrieval_log (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL,
  query          text        NOT NULL,
  filters        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  top_k          int         NOT NULL,
  hit_count      int         NOT NULL DEFAULT 0,
  hits           jsonb       NOT NULL DEFAULT '[]'::jsonb,
  latency_ms     int,
  actor_id       bigint,
  identity_level text        NOT NULL DEFAULT 'public',
  kind           text        NOT NULL DEFAULT 'TEST',
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT knowledge_retrieval_log_kind_ck CHECK (kind IN ('TEST','PROD')),
  CONSTRAINT knowledge_retrieval_log_identity_ck CHECK (identity_level IN ('public','customer','agent'))
);
CREATE INDEX IF NOT EXISTS knowledge_retrieval_log_time_idx
  ON knowledge.retrieval_log (tenant_id, created_at DESC);
COMMENT ON TABLE knowledge.retrieval_log IS '检索日志；kind 区分测试与生产调用，为三期留';
